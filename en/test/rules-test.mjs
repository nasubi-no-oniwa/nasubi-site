console.log('29秒待ちます…');await sleep(29000);
ex('60秒：記録する',await req('PUT',P+'b60/all/'+U3,U3,rec3(run6.st,20)),true);
ex('60秒：今日のほうに記録する',await req('PUT',P+'b60/d/'+U3,U3,recD3(run6.st,20)),true);
