ex('30秒：前より悪い記録',await req('PUT',P+'b30/all/'+U3,U3,rec3(run3.st,5)),false);
ex('30秒：名前だけ変える',await req('PUT',P+'b30/all/'+U3,U3,rec3(run3.st,9.5,'なまえ')),true);
ex('30秒のランキングはだれでも読める',await req('GET',P+'b30/all',null),true);
ex('60秒の組で回を始める',await req('PUT',P+'run/'+U3,U3,{st:TS,m:60}),true);
const run6=(await req('GET',P+'run/'+U3,U3)).j;
await sleep(27000);
