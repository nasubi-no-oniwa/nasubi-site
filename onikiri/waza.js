// 効果を言葉にする（技を選ぶ画面と表で同じ文を使う）
const WIDE = { 0: '自分のレーン', 1: '両隣まで', 2: '左右2レーンまで', 9: '全レーン' };
export function desc(p) {
  const o = p.O ? '。障害物も壊す' : '', g = p.G ? '。障害物もすり抜ける' : '', h = p.H ? '。切れ味が' + p.H + '回復' : '';
  if (p.k === 'inst') return `${WIDE[p.L]}の前${p.R}mを一気に斬る${o}${h}`;
  if (p.k === 'aura') return `${p.D}秒間、${WIDE[p.L]}で近づく鬼を斬り続ける（鬼に当たらない）${o}${g}`;
  if (p.k === 'flow') return `${p.D}秒間、自動で動いて${p.L >= 2 ? '広く' : ''}鬼を斬り進む（当たらない）${p.grow ? '。だんだん広がる' : ''}${o}`;
  if (p.k === 'multi') return `近い順に${p.N}体を斬る（前${p.R}mまで）`;
  if (p.k === 'rain') return `${p.D}秒間、全レーンの前${p.R}mに斬撃が降りそそぐ${o}`;
  if (p.k === 'slow') return `${p.D}秒間、まわりが遅くなる`;
  return '';
}
